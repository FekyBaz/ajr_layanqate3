-- 6. BACKFILL MESSAGE HASHES to SHA-256
-- ═══════════════════════════════════════════════════════════════════════════

CREATE EXTENSION IF NOT EXISTS pgcrypto;

UPDATE public.submissions
SET message_hash = encode(digest(message, 'sha256'), 'hex')
WHERE message_hash IS NOT NULL
  AND length(message_hash) = 32;

