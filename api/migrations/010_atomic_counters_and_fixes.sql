-- 3. FIX STATUS CHECK CONSTRAINT
-- ═══════════════════════════════════════════════════════════════════════════

DO $$
DECLARE
    existing_constraint_name text;
BEGIN
    SELECT conname INTO existing_constraint_name
    FROM pg_constraint
    WHERE conrelid = 'public.submissions'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) ILIKE '%status%'
    LIMIT 1;

    IF existing_constraint_name IS NOT NULL THEN
        EXECUTE format('ALTER TABLE public.submissions DROP CONSTRAINT %I', existing_constraint_name);
    END IF;

    ALTER TABLE public.submissions
        ADD CONSTRAINT submissions_status_check
        CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Posted'));
END $$;

