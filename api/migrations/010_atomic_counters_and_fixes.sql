CREATE TABLE IF NOT EXISTS public.view_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_hash text NOT NULL,
    submission_id uuid NOT NULL REFERENCES public.submissions(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_view_events_lookup
    ON public.view_events(ip_hash, submission_id, created_at DESC);

ALTER TABLE public.view_events ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE tablename = 'view_events'
          AND policyname = 'View events service role manage'
    ) THEN
        CREATE POLICY "View events service role manage"
            ON public.view_events
            FOR ALL
            USING (auth.role() = 'service_role')
            WITH CHECK (auth.role() = 'service_role');
    END IF;
END $$;

-- Atomic view increment with database-backed deduplication
CREATE OR REPLACE FUNCTION public.record_and_increment_view(
    p_submission_id uuid,
    p_ip_hash text,
    p_debounce_seconds integer DEFAULT 60
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
AS $$
DECLARE
    v_cutoff timestamptz;
    v_exists boolean;
    v_views integer;
BEGIN
    v_cutoff := now() - (p_debounce_seconds || ' seconds')::interval;

    SELECT EXISTS(
        SELECT 1 FROM public.view_events
        WHERE ip_hash = p_ip_hash
          AND submission_id = p_submission_id
          AND created_at > v_cutoff
    ) INTO v_exists;

    IF v_exists THEN
        RETURN jsonb_build_object('recorded', false, 'reason', 'debounced');
    END IF;

    INSERT INTO public.view_events (ip_hash, submission_id)
    VALUES (p_ip_hash, p_submission_id);

    UPDATE public.submissions
    SET views = views + 1
    WHERE id = p_submission_id
      AND status IN ('Approved', 'Posted')
    RETURNING views INTO v_views;

    IF v_views IS NULL THEN
        RETURN jsonb_build_object('recorded', false, 'reason', 'not_found');
    END IF;

    RETURN jsonb_build_object('recorded', true, 'views', v_views);
END;
$$;

-- Cleanup function for old view events
CREATE OR REPLACE FUNCTION public.cleanup_view_events(p_older_than_hours integer DEFAULT 24)
RETURNS integer
LANGUAGE sql
VOLATILE
SECURITY DEFINER
AS $$
    WITH deleted AS (
        DELETE FROM public.view_events
        WHERE created_at < now() - (p_older_than_hours || ' hours')::interval
        RETURNING 1
    )
    SELECT count(*)::integer FROM deleted;
$$;

