-- Atomic view increment
CREATE OR REPLACE FUNCTION public.increment_view(p_submission_id uuid)
RETURNS integer
LANGUAGE sql
VOLATILE
SECURITY DEFINER
AS $$
    UPDATE public.submissions
    SET views = views + 1
    WHERE id = p_submission_id
      AND status IN ('Approved', 'Posted')
    RETURNING views;
$$;

-- Atomic post_count increment
CREATE OR REPLACE FUNCTION public.increment_post_count(p_submission_id uuid)
RETURNS integer
LANGUAGE sql
VOLATILE
SECURITY DEFINER
AS $$
    UPDATE public.submissions
    SET post_count = post_count + 1,
        last_posted_at = now()
    WHERE id = p_submission_id
      AND status IN ('Approved', 'Posted')
    RETURNING post_count;
$$;

-- Atomic goal progress increment
CREATE OR REPLACE FUNCTION public.increment_goal_progress(p_date date, p_amount integer DEFAULT 1)
RETURNS integer
LANGUAGE sql
VOLATILE
SECURITY DEFINER
AS $$
    UPDATE public.community_goal
    SET current_progress = current_progress + p_amount,
        updated_at = timezone('utc', now())
    WHERE date = p_date
    RETURNING current_progress;
$$;

